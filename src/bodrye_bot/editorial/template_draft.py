from __future__ import annotations


class TemplateDraftWriter:
    """Deterministic draft so the first loop works without a live model call."""

    def write(self, topic: str) -> str:
        title = topic.strip() or "тема дня"
        return (
            f"Тема: {title}\n\n"
            "Коротко. После 35 телу чаще не хватает не героизма, а спокойного ритма: "
            "сон, еда без войны с собой и немного движения в обычный день.\n\n"
            "Что это значит. Можно выбрать один маленький шаг, который реально влезает "
            "в рабочую неделю — без обещания «перезапустить организм за три дня».\n\n"
            "Маленький шаг. Завтра отметьте, во сколько вы легли и встали. Это уже данные, "
            "а не характер.\n\n"
            "Важно: это не медицинская рекомендация и не диагноз. Перед публикацией Кети "
            "проверяет факты вручную."
        )
